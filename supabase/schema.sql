create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  date_of_birth date,
  state text,
  district text,
  occupation text,
  annual_family_income text,
  education_level text,
  residence_type text,
  role text not null default 'citizen' check (role in ('citizen', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.scheme_categories (
  id text primary key,
  name text not null,
  name_te text,
  is_active boolean not null default true
);

create table if not exists public.schemes (
  id text primary key,
  name text not null,
  name_te text,
  government_level text not null default 'Central',
  department text not null,
  description text not null default '',
  benefit text,
  category text references public.scheme_categories(id),
  state text not null default 'All India',
  official_url text,
  source_reference text,
  last_verified date,
  criteria_complete boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.saved_schemes (
  user_id uuid not null references auth.users(id) on delete cascade,
  scheme_id text not null,
  saved_at timestamptz not null default now(),
  primary key (user_id, scheme_id)
);

create table if not exists public.user_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  scheme_id text,
  activity_type text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.user_application_tracking (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  scheme_id text not null,
  status text not null default 'not_started' check (status in ('not_started', 'preparing_documents', 'submitted')),
  notes text not null default '',
  visited_official_portal boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (user_id, scheme_id)
);

create index if not exists saved_schemes_user_idx on public.saved_schemes(user_id);
create index if not exists user_activity_user_idx on public.user_activity(user_id, created_at desc);
create index if not exists application_tracking_user_idx on public.user_application_tracking(user_id);

