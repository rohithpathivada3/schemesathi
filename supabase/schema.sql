create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$ select exists (
  select 1 from public.profiles
  where id = auth.uid() and role = 'admin'
) $$;

create policy "profiles_select_own" on public.profiles for select using (auth.uid() = id);
create policy "profiles_insert_own" on public.profiles for insert with check (auth.uid() = id);
create policy "profiles_update_own" on public.profiles for update using (auth.uid() = id)
  with check (auth.uid() = id and role = (select role from public.profiles where id = auth.uid()));

create policy "categories_public_read" on public.scheme_categories for select using (is_active);
create policy "categories_admin_manage" on public.scheme_categories for all using (public.is_admin()) with check (public.is_admin());
create policy "schemes_public_read" on public.schemes for select using (is_active);
create policy "schemes_admin_manage" on public.schemes for all using (public.is_admin()) with check (public.is_admin());

create policy "saved_select_own" on public.saved_schemes for select using (auth.uid() = user_id);
create policy "saved_insert_own" on public.saved_schemes for insert with check (auth.uid() = user_id);
create policy "saved_delete_own" on public.saved_schemes for delete using (auth.uid() = user_id);

create policy "activity_select_own" on public.user_activity for select using (auth.uid() = user_id);
create policy "activity_insert_own" on public.user_activity for insert with check (auth.uid() = user_id);
create policy "activity_delete_own" on public.user_activity for delete using (auth.uid() = user_id);

create policy "tracking_select_own" on public.user_application_tracking for select using (auth.uid() = user_id);
create policy "tracking_insert_own" on public.user_application_tracking for insert with check (auth.uid() = user_id);
create policy "tracking_update_own" on public.user_application_tracking for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "tracking_delete_own" on public.user_application_tracking for delete using (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.delete_current_user()
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  delete from auth.users where id = auth.uid();
end;
$$;

grant execute on function public.delete_current_user() to authenticated;

